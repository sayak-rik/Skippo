# ---------------------------------------------------------------------------
# Demo in-memory state
#
# All backend views run in demo mode — no database queries are made.
# This module owns the single mutable STATE dict that simulates a real school's
# data.  Every view function reads/writes this dict via the helpers below.
#
# Sections of STATE:
#   users               – login payloads keyed by role
#   student/trip/vehicle/students/renewals/devices  – driver + parent domains
#   messages/alerts/progress/dailyReports           – parent feed domain
#   schedule/roster/teacherDailyPreview             – teacher attendance domain
#   classrooms          – full list of classrooms for the class-picker feature
#   broadcasts          – class-wide broadcast messages sent by teachers
#   assistRequests      – parent-raised doubt/help cards per student
#   teacherInvites      – invite tokens generated by admin dashboard
#   schedulePreferences – teacher's saved weekly schedule (first-week setup)
#   sosEvents           – SOS events from driver app
#   breakdownEvents     – Breakdown events from driver app
#   availableRoutes     – routes parents can assign their ward to
#   driverContact       – current trip driver's contact info
#   studentStopOverrides – parent-customised pick-up/drop-off stops per student
#   firstTripConfirmations – pending stop auto-assignment confirmations
#   locationPings       – latest 1-min GPS ping per trip (req 1)
#   tripHistory         – completed trip records saved to "DB" (req 2)
#   nearbyVehicles      – other school buses visible in breakdown mode (req 12)
#   driverInvites       – admin-generated driver invite tokens
#   driverSignupRequests – self-signup requests pending admin approval
#   driverVehicles      – all vehicles assigned to the demo driver (multi-vehicle, req 13)
# ---------------------------------------------------------------------------


