# ── First-trip stop auto-assignment (req 8) ───────────────────────────────────

def _check_first_trip(student_id: int, latitude: float, longitude: float, stop_name: str) -> dict | None:
    """If this is the student's first-ever board event, create a pending confirmation.

    Both parent and driver must confirm before the stop is permanently saved.
    Returns the pending confirmation record, or None if already confirmed/exists.
    """
    key = str(student_id)
    if key in STATE["studentStopOverrides"] or key in STATE["firstTripConfirmations"]:
        return None

    confirmation = {
        "status": "pending",
        "stopName": stop_name,
        "latitude": latitude,
        "longitude": longitude,
    }
    STATE["firstTripConfirmations"][key] = confirmation

    # Inject a parent notification asking them to confirm the pickup location
    student = next((s for s in STATE["students"] if s["id"] == student_id), None)
    student_name = student["name"] if student else f"Student #{student_id}"
    STATE["alerts"].insert(0, {
        "id": 500 + student_id,
        "title": "Confirm pickup location",
        "body": (
            f"{student_name} was picked up for the first time at {stop_name}. "
            "Please confirm this as your scheduled pickup point."
        ),
        "level": "warning",
        "createdAt": "2026-04-17T07:30:00+05:30",
        "actionType": "confirm_stop",
        "studentId": student_id,
    })
    return deepcopy(confirmation)


