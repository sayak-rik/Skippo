class AcceptInviteView(APIView):
    """Complete teacher signup via an invite token.

    POST /api/auth/teacher/accept-invite/
    Body: { "token": "...", "name": "...", "phone": "..." }
    """

    permission_classes = [permissions.AllowAny]

    def post(self, request):
        token = request.data.get("token", "").strip()
        name = request.data.get("name", "").strip()
        phone = request.data.get("phone", "").strip()

        if not token or not name or not phone:
            return Response(
                {"detail": "token, name, and phone are all required."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        payload = accept_invite(token, name=name, phone=phone)
        if payload is None:
            return Response(
                {"detail": "Invite not found or already used."},
                status=status.HTTP_404_NOT_FOUND,
            )
        return Response(payload, status=status.HTTP_201_CREATED)


