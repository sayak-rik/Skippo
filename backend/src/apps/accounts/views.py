User = get_user_model()

_OTP_TTL_MINUTES = 10
_OTP_MAX_ATTEMPTS = 5


def _generate_otp() -> str:
    return "".join(random.choices(string.digits, k=6))


def _hash_code(code: str) -> str:
    return hashlib.sha256(code.encode()).hexdigest()


def _jwt_for_user(user) -> dict:
    refresh = RefreshToken.for_user(user)
    return {"refresh": str(refresh), "access": str(refresh.access_token)}


class AdminLoginView(APIView):
    """Email + password login for staff and superusers. Returns JWT tokens."""

    authentication_classes = []
    permission_classes = [permissions.AllowAny]

    def post(self, request):
        email = (request.data.get("email") or "").strip().lower()
        password = request.data.get("password", "")
        if not email or not password:
            return Response({"detail": "email and password are required."}, status=400)

        # Prefer superuser > staff when duplicates exist (data-level deduplication pending)
        user = (
            User.objects
            .filter(email__iexact=email)
            .order_by("-is_superuser", "-is_staff", "id")
            .first()
        )
        if user is None:
            return Response({"detail": "Invalid credentials."}, status=401)

        if not user.check_password(password):
            return Response({"detail": "Invalid credentials."}, status=401)

        if not user.is_staff:
            return Response({"detail": "Access denied. Staff only."}, status=403)

        tokens = _jwt_for_user(user)
        return Response({
            **tokens,
            "role": "superuser" if user.is_superuser else "staff",
            "name": user.get_full_name() or user.email,
            "email": user.email,
            "id": user.id,
        })


