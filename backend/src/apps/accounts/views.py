class OTPRequestView(APIView):
    """Send a 6-digit OTP to the parent/driver's phone via SMS or email.

    POST /api/auth/otp/request/
    Body:
        contact     (str) – phone number or email address
        channel     (str) – "sms" or "email"
        role        (str) – "parent" or "driver"
        school_slug (str) – school identifier
        purpose     (str, optional) – "login" (default) or "confirm_action"
        context     (obj, optional) – extra payload stored on the OTP record
    """

    permission_classes = [permissions.AllowAny]

    def post(self, request):
        import logging
        log = logging.getLogger(__name__)

        contact = request.data.get("contact", "").strip()
        channel = request.data.get("channel", "sms")
        role = request.data.get("role", "")
        school_slug = request.data.get("school_slug", "").strip()
        purpose = request.data.get("purpose", OTPRequest.Purpose.LOGIN)
        context = request.data.get("context", {})

        if not contact or role not in ("parent", "driver", "teacher", "admin") or not school_slug:
            return Response(
                {"detail": "contact, role, and school_slug are required."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        if channel not in ("sms", "email"):
            return Response(
                {"detail": "channel must be 'sms' or 'email'."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        try:
            school = School.objects.get(slug=school_slug, is_active=True)
        except School.DoesNotExist:
            return Response({"detail": "School not found."}, status=status.HTTP_404_NOT_FOUND)

        # Verify the contact exists for the given role + school
        fallback_email = None  # used for SMS→email fallback
        if role == "admin":
            user = (
                User.objects
                .filter(email__iexact=contact, default_school=school)
                .first()
            )
            if user is None:
                return Response(
                    {"detail": "No admin account found for this email at the given school."},
                    status=status.HTTP_404_NOT_FOUND,
                )
        elif role == "parent":
            profile = ParentProfile.objects.filter(school=school, phone=contact).select_related("user").first()
            if profile is None:
                # Allow OTP for pending parents (admin-imported, not yet signed up)
                from apps.academics.models import Student
                if not Student.objects.filter(school=school, pending_parent_phone=contact).exists():
                    return Response(
                        {"detail": "No account found for this contact at the given school."},
                        status=status.HTTP_404_NOT_FOUND,
                    )
            else:
                fallback_email = profile.user.email or None
        elif role == "teacher":
            profile = TeacherProfile.objects.filter(school=school, user__phone=contact, is_active=True).select_related("user").first()
            if profile is None:
                return Response(
                    {"detail": "No account found for this contact at the given school."},
                    status=status.HTTP_404_NOT_FOUND,
                )
            fallback_email = profile.user.email or None
        else:  # driver
            profile = DriverProfile.objects.filter(school=school, phone=contact).select_related("user").first()
            if profile is None:
                return Response(
                    {"detail": "No account found for this contact at the given school."},
                    status=status.HTTP_404_NOT_FOUND,
                )
            fallback_email = profile.user.email or None

        code = _generate_otp()
        OTPRequest.objects.create(
            school=school,
            contact=contact,
            channel=channel,
            role=role,
            purpose=purpose,
            code_hash=_hash_code(code),
            expires_at=timezone.now() + timedelta(minutes=_OTP_TTL_MINUTES),
            context=context if isinstance(context, dict) else {},
        )

        if channel == "email" or role == "admin":
            # For admin the contact IS the email; for email channel contact is the email address.
            send_otp_email(to=contact, code=code, ttl_minutes=_OTP_TTL_MINUTES, school_name=school.name)
        else:
            # SMS channel — try MSG91, fall back to email if it fails
            sms_ok = send_sms(to=contact, message=f"Your Skippo OTP is {code}. Valid for {_OTP_TTL_MINUTES} minutes.")
            if not sms_ok:
                log.warning("SMS failed for %s; attempting email fallback", contact)
                if fallback_email:
                    send_otp_email(to=fallback_email, code=code, ttl_minutes=_OTP_TTL_MINUTES, school_name=school.name)
                else:
                    log.warning("No fallback email found for contact %s", contact)

        return Response({"detail": "OTP sent."}, status=status.HTTP_200_OK)


class OTPVerifyView(APIView):
    """Verify an OTP and return JWT tokens on success.

    POST /api/auth/otp/verify/
    Body:
        contact     (str)
        code        (str) – the 6-digit OTP
        role        (str)
        school_slug (str)
        purpose     (str, optional) – must match what was requested

    Returns on login purpose:
        { "access": "...", "refresh": "...", "role": "parent"|"driver" }

    Returns on confirm_action purpose:
        { "confirmed": true }
    """

    permission_classes = [permissions.AllowAny]

    def post(self, request):
        contact = request.data.get("contact", "").strip()
        code = request.data.get("code", "").strip()
        role = request.data.get("role", "")
        school_slug = request.data.get("school_slug", "").strip()
        purpose = request.data.get("purpose", OTPRequest.Purpose.LOGIN)

        if not contact or not code or role not in ("parent", "driver", "teacher", "admin") or not school_slug:
            return Response(
                {"detail": "contact, code, role, and school_slug are required."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        try:
            school = School.objects.get(slug=school_slug)
        except School.DoesNotExist:
            return Response({"detail": "School not found."}, status=status.HTTP_404_NOT_FOUND)

        otp = (
            OTPRequest.objects.filter(
                school=school,
                contact=contact,
                role=role,
                purpose=purpose,
                is_used=False,
                expires_at__gt=timezone.now(),
                attempts__lt=_OTP_MAX_ATTEMPTS,
            )
            .order_by("-created_at")
            .first()
        )

        if otp is None:
            return Response(
                {"detail": "No valid OTP found. Please request a new one."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        if otp.code_hash != _hash_code(code):
            otp.attempts += 1
            otp.save(update_fields=["attempts"])
            remaining = _OTP_MAX_ATTEMPTS - otp.attempts
            return Response(
                {"detail": f"Incorrect code. {remaining} attempt(s) remaining."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        otp.is_used = True
        otp.save(update_fields=["is_used"])

        if purpose == OTPRequest.Purpose.CONFIRM_ACTION:
            return Response({"confirmed": True, "context": otp.context})

        # Login purpose — look up the profile and return JWT tokens
        email_from_request = (request.data.get("email") or "").strip().lower()

        if role == "admin":
            user = User.objects.filter(email__iexact=contact, default_school=school).first()
            if user is None:
                return Response({"detail": "Profile not found."}, status=status.HTTP_404_NOT_FOUND)
        elif role == "parent":
            profile = (
                ParentProfile.objects
                .filter(school=school, phone=contact)
                .select_related("user")
                .first()
            )
            if profile is None:
                # Signup path: phone verified — auto-create account and link student(s)
                from apps.academics.models import Student, StudentParentLink
                students = list(
                    Student.objects.filter(school=school, pending_parent_phone=contact)
                )
                if not students:
                    return Response(
                        {"detail": "No pending enrollment found. Please contact your school admin."},
                        status=status.HTTP_404_NOT_FOUND,
                    )
                pending_name = students[0].pending_parent_name or ""
                parts = pending_name.split(" ", 1)
                user = User(
                    username=f"parent_{contact.lstrip('+')}",
                    phone=contact,
                    first_name=parts[0],
                    last_name=parts[1] if len(parts) > 1 else "",
                    default_school=school,
                    email=email_from_request,
                )
                user.set_unusable_password()
                user.save()
                profile = ParentProfile.objects.create(school=school, user=user, phone=contact)
                for s in students:
                    StudentParentLink.objects.get_or_create(
                        student=s,
                        parent=profile,
                        defaults={
                            "is_primary": True,
                            "source": StudentParentLink.Source.ADMIN,
                            "school": school,
                        },
                    )
                    s.pending_parent_phone = ""
                    s.pending_parent_name = ""
                    s.save(update_fields=["pending_parent_phone", "pending_parent_name"])
            user = profile.user
        elif role == "teacher":
            profile = (
                TeacherProfile.objects
                .filter(school=school, user__phone=contact, is_active=True)
                .select_related("user")
                .first()
            )
            if profile is None:
                return Response({"detail": "Profile not found."}, status=status.HTTP_404_NOT_FOUND)
            user = profile.user
            tokens = _jwt_for_user(user)
            return Response({
                **tokens,
                "role": "teacher",
                "name": user.get_full_name(),
                "school_slug": school.slug,
                "school_name": school.name,
            })
        else:
            try:
                profile = DriverProfile.objects.select_related("user").get(school=school, phone=contact)
            except DriverProfile.DoesNotExist:
                return Response({"detail": "Profile not found."}, status=status.HTTP_404_NOT_FOUND)
            if not profile.is_approved:
                return Response(
                    {"detail": "Your account is pending approval."},
                    status=status.HTTP_403_FORBIDDEN,
                )
            user = profile.user

        tokens = _jwt_for_user(user)
        needs_profile_completion = role == "parent" and not user.get_full_name().strip()
        return Response({
            **tokens,
            "role": role,
            "user": {"id": user.id, "name": user.get_full_name()},
            "school_slug": school.slug,
            "needs_profile_completion": needs_profile_completion,
        })


class PasswordResetRequestView(APIView):
    """Send a 6-digit OTP to the admin's email for password reset.

    POST /api/auth/password/reset-request/
    Body:
        email       (str) – the admin's email address
        school_slug (str) – school identifier
    """

    permission_classes = [permissions.AllowAny]

    def post(self, request):
        import logging
        log = logging.getLogger(__name__)

        email = request.data.get("email", "").strip().lower()
        school_slug = request.data.get("school_slug", "").strip()

        if not email or not school_slug:
            return Response({"detail": "email and school_slug are required."}, status=status.HTTP_400_BAD_REQUEST)

        try:
            school = School.objects.get(slug=school_slug, is_active=True)
        except School.DoesNotExist:
            return Response({"detail": "School not found."}, status=status.HTTP_404_NOT_FOUND)

        user = User.objects.filter(email__iexact=email, default_school=school).first()
        if user is None:
            # Don't reveal whether the email exists
            return Response({"detail": "If that email is registered, a reset code has been sent."}, status=status.HTTP_200_OK)

        code = _generate_otp()
        OTPRequest.objects.create(
            school=school,
            contact=email,
            channel=OTPRequest.Channel.EMAIL,
            role=OTPRequest.Role.ADMIN,
            purpose=OTPRequest.Purpose.PASSWORD_RESET,
            code_hash=_hash_code(code),
            expires_at=timezone.now() + timedelta(minutes=_OTP_TTL_MINUTES),
        )
        send_otp_email(to=email, code=code, ttl_minutes=_OTP_TTL_MINUTES, school_name=school.name)
        log.info("Password reset OTP sent to %s", email)
        return Response({"detail": "If that email is registered, a reset code has been sent."}, status=status.HTTP_200_OK)


class PasswordResetConfirmView(APIView):
    """Verify the OTP and set a new password.

    POST /api/auth/password/reset-confirm/
    Body:
        email        (str) – the admin's email address
        school_slug  (str) – school identifier
        code         (str) – the 6-digit OTP
        new_password (str) – the new password (min 8 chars)
    """

    permission_classes = [permissions.AllowAny]

    def post(self, request):
        email = request.data.get("email", "").strip().lower()
        school_slug = request.data.get("school_slug", "").strip()
        code = request.data.get("code", "").strip()
        new_password = request.data.get("new_password", "")

        if not email or not school_slug or not code or not new_password:
            return Response({"detail": "email, school_slug, code, and new_password are required."}, status=status.HTTP_400_BAD_REQUEST)

        if len(new_password) < 8:
            return Response({"detail": "Password must be at least 8 characters."}, status=status.HTTP_400_BAD_REQUEST)

        try:
            school = School.objects.get(slug=school_slug)
        except School.DoesNotExist:
            return Response({"detail": "School not found."}, status=status.HTTP_404_NOT_FOUND)

        otp = (
            OTPRequest.objects.filter(
                school=school,
                contact=email,
                role=OTPRequest.Role.ADMIN,
                purpose=OTPRequest.Purpose.PASSWORD_RESET,
                is_used=False,
                expires_at__gt=timezone.now(),
                attempts__lt=_OTP_MAX_ATTEMPTS,
            )
            .order_by("-created_at")
            .first()
        )

        if otp is None:
            return Response({"detail": "No valid reset code found. Please request a new one."}, status=status.HTTP_400_BAD_REQUEST)

        if otp.code_hash != _hash_code(code):
            otp.attempts += 1
            otp.save(update_fields=["attempts"])
            remaining = _OTP_MAX_ATTEMPTS - otp.attempts
            return Response({"detail": f"Incorrect code. {remaining} attempt(s) remaining."}, status=status.HTTP_400_BAD_REQUEST)

        otp.is_used = True
        otp.save(update_fields=["is_used"])

        user = User.objects.filter(email__iexact=email, default_school=school).first()
        if user is None:
            return Response({"detail": "User not found."}, status=status.HTTP_404_NOT_FOUND)

        user.set_password(new_password)
        user.save(update_fields=["password"])

        return Response({"detail": "Password updated successfully."}, status=status.HTTP_200_OK)


