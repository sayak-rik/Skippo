def _mask_phone(phone: str) -> str:
    """Return a privacy-safe representation like +91 ****7821."""
    stripped = phone.lstrip("+")
    if len(stripped) <= 4:
        return "****"
    return f"+{stripped[:2]} ****{stripped[-4:]}"


